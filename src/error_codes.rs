//! Catálogo de errores de la API. Cada error tiene un código estable, que el frontend traduce,
//! y un mensaje base; las partes variables se escriben `$1`, `$2`… y viajan en `params`.

use crate::error::ErrorCode;

macro_rules! error_codes {
    ($($(#[$doc:meta])* $name:ident => $message:literal,)*) => {
        $($(#[$doc])* pub const $name: ErrorCode = ErrorCode { code: stringify!($name), message: $message };)*

        /// Todos los códigos: permiten reconocer los mensajes que llegan desde la base de datos.
        pub const ALL: &[ErrorCode] = &[$($name),*];
    };
}

